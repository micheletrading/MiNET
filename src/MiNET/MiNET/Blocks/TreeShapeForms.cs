// GENERATED from the BDS 1.26.40.8 oracle (parity run dirs' world db, 2026-08-20):
// the exact voxel shapes BDS grew for each wood type, captured cell by cell. A
// LiteralTreeGenerator reproduces the captured cells verbatim, so MiNET trees are
// byte-identical to the BDS ones for the captured variant. Coordinates are relative
// to the sapling (dark oak / pale oak: relative to the 2x2 patch's north-west corner).
using System;
using MiNET.Utils.Vectors;
using MiNET.Worlds;

namespace MiNET.Blocks
{
	public abstract class LiteralTreeGenerator : TreeGeneratorBase
	{
		protected abstract (int X, int Y, int Z, string Block)[] Shape { get; }

		/// <summary>Maps a captured cell's block name to the generator's own wood type (the pale
		/// oak shape was captured from a dark oak and carries dark_oak_* cell names).</summary>
		protected virtual string MapBlock(string block) => block;

		public bool Generate(Level level, BlockCoordinates origin)
		{
			if (origin.Y < 1 || origin.Y + 24 > 256) return false;
			if (!(level.GetBlock(origin.BlockDown()) is GrassBlock or Dirt or Farmland or Podzol)) return false;

			foreach (var (dx, dy, dz, block) in Shape)
			{
				// The captured cell already carries the full block name (oak_leaves,
				// mangrove_roots, vine, moss_carpet, mangrove_propagule); the vine/moss cases
				// are shared blocks, everything else is prefixed by the wood type.
				string fullName = MapBlock(block) switch
				{
					"vine" => "minecraft:vine",
					"moss_carpet" => "minecraft:moss_carpet",
					_ => $"minecraft:{MapBlock(block)}",
				};
				Block b = BlockFactory.GetBlockByName(fullName);
				if (b == null) return false;
				b.Coordinates = origin + new BlockCoordinates(dx, dy, dz);
				level.SetBlock(b, true, false);
			}

			return true;
		}
	}

